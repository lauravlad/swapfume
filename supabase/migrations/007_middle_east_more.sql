-- Run AFTER 006. Safe to run more than once:
--   * adds catalog perfumes that aren't there yet (existing ones are skipped, no duplicates)
--   * fills in a release year only where the database has none and the catalog file knows it
--   * perfumes whose year we don't know stay in the catalog and show "Year unknown";
--     admins can fill the year in later from the perfume's page
-- =====================================================================

-- Admins set or clear a perfume's release year. The "Classic" flag follows the year.
create or replace function public.admin_set_perfume_year(p_perfume bigint, p_year int)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admins only.'; end if;
  if p_year is not null and (p_year < 1700 or p_year > 2100) then raise exception 'That year looks off.'; end if;
  update public.perfumes
     set year = p_year,
         is_classic = coalesce(p_year < 2000, false)
   where id = p_perfume;
end;
$$;
revoke execute on function public.admin_set_perfume_year(bigint, int) from public, anon;
grant execute on function public.admin_set_perfume_year(bigint, int) to authenticated;

